"""Embed our single trusted verifier and registry; no launcher JS is copied."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
registry=json.loads((root/'CEF_CONTRACT.json').read_text('utf-8-sig'))
engine=(root/'tools/cef-contract-engine.ps1').read_text('utf-8-sig')
adapter=(root/'cef/assets/hud/pa26-chat.js').read_bytes().decode('utf-8')
# Lua long strings normalize line endings. Restore CRLF when that is how the
# distributed adapter is stored so recovery copies exactly the same bytes.
ending=''
if '\r' in adapter:
    assert adapter.count('\r\n')==adapter.count('\r')==adapter.count('\n')
    adapter=adapter.replace('\r\n','\n')
    ending=r":gsub('\n','\r\n')"
data=json.dumps(registry,ensure_ascii=False,separators=(',',':'))
assert ']====]' not in data+engine+adapter
(root/'moonloader/lib/pa26_cef_contract.lua').write_text(
    '-- Generated by tools/build-cef-contract0450.py. PA-owned verifier, never launcher code.\n'
    'return {registry=[====['+data+']====], verifier=[====['+engine+']====],\n'
    ' adapter=([====['+adapter+']====])'+ending+'}\n','utf-8',newline='\n')
print('Shared CEF verifier and registry embedded.')
