"""Pin Free Solid metadata and reproduce the old-worker-compatible font carrier."""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'moonloader/resource/pa26/fonts'
FONT_SHA = 'af19d135d3a935b3ebfbd80320716ffe1202052c5f68dc2c5f1abc57005ac605'
LICENSE_SHA = '9b914eae88817d63b576eab5aafde7068c7a1abae125d7cdfb034f1da43a9afc'
font = (ASSETS / 'fa-solid-900.ttf').read_bytes()
license_bytes = (ASSETS / 'LICENSE.txt').read_bytes()
assert hashlib.sha256(font).hexdigest() == FONT_SHA
assert hashlib.sha256(license_bytes).hexdigest() == LICENSE_SHA
names = ['house','car-side','route','tower-broadcast','bullhorn','triangle-exclamation',
         'circle-info','circle-check','circle-xmark','magnifying-glass','gear','book-open',
         'scale-balanced','gavel','users','id-card','crosshairs','clipboard-list','play','pause',
         'flag-checkered','stop','paper-plane','check','xmark','pen','floppy-disk','rotate',
         'location-dot','clock','arrow-left','chevron-down','shield-halved','car-burst',
         'phone','file-lines','keyboard','sliders','circle-question','handcuffs']
upstream = ROOT / 'tests/font-upstream/icons.json'
if upstream.exists():
    metadata = json.loads(upstream.read_text('utf-8'))
    icons = {}
    for name in names:
        row = metadata[name]
        assert 'solid' in row['free'], (name, 'not in Free Solid')
        cp = int(row['unicode'], 16)
        assert 0xE000 <= cp <= 0xFFFF
        icons[name] = {'codepoint': row['unicode'], 'family': 'Free Solid'}
    manifest = {'library': 'Font Awesome Free', 'version': '6.7.2', 'style': 'solid',
                'font': 'fa-solid-900.ttf', 'sha256': FONT_SHA, 'bytes': len(font),
                'license': 'SIL Open Font License 1.1', 'license_sha256': LICENSE_SHA,
                'source': 'https://github.com/FortAwesome/Font-Awesome/releases/tag/6.7.2',
                'font_source': 'https://raw.githubusercontent.com/FortAwesome/Font-Awesome/6.7.2/webfonts/fa-solid-900.ttf',
                'metadata_source': 'https://raw.githubusercontent.com/FortAwesome/Font-Awesome/6.7.2/metadata/icons.json',
                'metadata_sha256': hashlib.sha256(upstream.read_bytes()).hexdigest(),
                'icons': icons,
                'update_transport': 'Identical original bytes and original license in lib/pa26_icon_font.lua; no worker/platform changes.'}
    (ASSETS / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n', encoding='utf-8', newline='\n')
else:
    manifest = json.loads((ASSETS / 'manifest.json').read_text('utf-8'))
    assert set(manifest['icons']) == set(names)
    assert manifest['sha256'] == FONT_SHA and manifest['license_sha256'] == LICENSE_SHA

header = '-- GENERATED by tools/build-icons.py. Original Font Awesome Free 6.7.2 font, unmodified.\n'
pieces = ["'" + ''.join('\\%03d' % b for b in font[i:i+512]) + "'" for i in range(0,len(font),512)]
carrier = header + "return {sha256='"+FONT_SHA+"',data=table.concat({\n"+',\n'.join(pieces)+"\n}),license=[==["+license_bytes.decode('utf-8')+"]==],manifest=[==["+(ASSETS / 'manifest.json').read_text('utf-8')+"]==]}\n"
(ROOT / 'moonloader/lib/pa26_icon_font.lua').write_text(carrier, encoding='utf-8', newline='\n')
rows = ['-- GENERATED verified Free Solid codepoints; presentation only.', 'return {']
for name, row in manifest['icons'].items():
    rows.append(" ['"+name+"']="+str(int(row['codepoint'],16))+',')
rows.append('}\n')
(ROOT / 'moonloader/lib/pa26_icon_glyphs.lua').write_text('\n'.join(rows), encoding='utf-8', newline='\n')
print(f'Font Awesome Free 6.7.2: {len(names)} verified Solid mappings; {len(font)} original font bytes; license/carrier pinned.')
